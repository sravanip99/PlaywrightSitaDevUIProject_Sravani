//For Loop
//for (initialization; condition; increment/decrement) {
for (let i = 0; i < 5; i++) {
    console.log(i);
}
//addition of two numbers using for loop    
let sum = 0;
for (let i = 0; i <= 10 ; i++) {
    sum+=i;
}
console.log("Sum of numbers from 0 to 10 is: " + sum);  

//While Loop
let j = 0;  
while (j < 5) {
    console.log(j); 
    j++;    
}

//Do While Loop
let k = 100;
do {
    console.log(k);
    k++;
} while (k < 105);    
